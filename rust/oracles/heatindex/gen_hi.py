"""Generate the heat index oracle: a C++ shim over the real EnergyPlus extended heat index
(namespace ExtendedHI, ExtendedHeatIndex.cc) and a C unit that rust-anything can bridge.
Usage: python gen_hi.py <out_dir>

Exported: the seven plain-number helpers, each step heatindex takes (the four find_eqvar_*
functions, find_eqvar_name_and_value split into its value and its name, and find_T), and
heatindex itself. The steps run under the root-finding algorithm heatindex selects
(ShortBisectionThenRegulaFalsi), so each one gives exactly what it gives inside heatindex."""

import sys
from pathlib import Path

HEADER = "// Generated by gen_hi.py. Do not edit by hand.\n"

# (C name, return type, params, C++ call). "S" marks a call that needs the state and the
# heat index's root-finding algorithm.
FUNCS = [
    ("pvstar", "double", ["T"], "ExtendedHI::pvstar(T)"),
    ("Le", "double", ["T"], "ExtendedHI::Le(T)"),
    ("Qv", "double", ["Ta", "Pa"], "ExtendedHI::Qv(Ta, Pa)"),
    ("Zs", "double", ["Rs"], "ExtendedHI::Zs(Rs)"),
    ("Ra", "double", ["Ts", "Ta"], "ExtendedHI::Ra(Ts, Ta)"),
    ("Ra_bar", "double", ["Tf", "Ta"], "ExtendedHI::Ra_bar(Tf, Ta)"),
    ("Ra_un", "double", ["Ts", "Ta"], "ExtendedHI::Ra_un(Ts, Ta)"),
    ("find_eqvar_phi", "double", ["Ta", "RH"], "S ExtendedHI::find_eqvar_phi(st(), Ta, RH)"),
    ("find_eqvar_Rf", "double", ["Ta", "RH"], "S ExtendedHI::find_eqvar_Rf(st(), Ta, RH)"),
    ("find_eqvar_rs", "double", ["Ta", "RH"], "S ExtendedHI::find_eqvar_rs(st(), Ta, RH)"),
    ("find_eqvar_dTcdt", "double", ["Ta", "RH"], "S ExtendedHI::find_eqvar_dTcdt(st(), Ta, RH)"),
    ("find_eqvar_value", "double", ["Ta", "RH"],
     "S ExtendedHI::find_eqvar_name_and_value(st(), Ta, RH, name)"),
    ("find_eqvar_name", "int", ["Ta", "RH"],
     "S (ExtendedHI::find_eqvar_name_and_value(st(), Ta, RH, name), static_cast<int>(name))"),
    ("find_T", "double", ["eqvar_name", "eqvar"],
     "S ExtendedHI::find_T(st(), static_cast<ExtendedHI::EqvarName>(eqvar_name), eqvar)"),
    ("heatindex", "double", ["Ta", "RH"], "ExtendedHI::heatindex(st(), Ta, RH)"),
]
INT_PARAMS = {"eqvar_name"}


def params(ps):
    return ", ".join(f"{'int' if p in INT_PARAMS else 'double'} {p}" for p in ps)


def shim():
    out = [HEADER, """// Plain extern "C" entry points over the real EnergyPlus extended heat index. One
// EnergyPlusData for the process, built when the library loads so each forked case starts from
// the same untouched state.
#include <EnergyPlus/Data/EnergyPlusData.hh>
#include <EnergyPlus/ExtendedHeatIndex.hh>
#include <EnergyPlus/HVACSystemRootFindingAlgorithm.hh>

using namespace EnergyPlus;

namespace EnergyPlus::ExtendedHI {
// Defined in ExtendedHeatIndex.cc but not declared in its header.
Real64 find_eqvar_dTcdt(EnergyPlusData &state, Real64 const Ta, Real64 const RH);
} // namespace EnergyPlus::ExtendedHI

namespace {
EnergyPlusData &st()
{
    static EnergyPlusData *s = [] { return new EnergyPlusData; }();
    return *s;
}
[[maybe_unused]] EnergyPlusData &loaded = st();

// Runs a step under the root-finding algorithm heatindex selects, then restores the old one.
template <class F> auto as_in_heatindex(F f)
{
    RootAlgo const backup = st().dataRootFinder->rootAlgo;
    st().dataRootFinder->rootAlgo = RootAlgo::ShortBisectionThenRegulaFalsi;
    auto const r = f();
    st().dataRootFinder->rootAlgo = backup;
    return r;
}
} // namespace

extern "C" {
"""]
    for name, ret, ps, call in FUNCS:
        if call.startswith("S "):
            body = (f"    ExtendedHI::EqvarName name = ExtendedHI::EqvarName::Invalid;\n"
                    f"    (void)name;\n"
                    f"    return as_in_heatindex([&] {{ return {call[2:]}; }});\n")
        else:
            body = f"    return {call};\n"
        out.append(f"{ret} ep_{name}({params(ps)})\n{{\n{body}}}\n\n")
    out.append("}\n")
    return "".join(out)


def c_header():
    out = [HEADER, "#ifndef EP_HEATINDEX_H\n#define EP_HEATINDEX_H\n\n"]
    out += [f"{ret} {name}({params(ps)});\n" for name, ret, ps, _ in FUNCS]
    out.append("\n#endif\n")
    return "".join(out)


def c_unit():
    out = [HEADER, """// The heat index unit as rust-anything sees it: each function forwards to the real
// EnergyPlus ExtendedHI function through libep_hi_shim (shim/ep_hi_shim.cc).
#include "heatindex.h"

"""]
    out += [f"{ret} ep_{name}({params(ps)});\n" for name, ret, ps, _ in FUNCS]
    out.append("\n")
    for name, ret, ps, _ in FUNCS:
        out.append(f"{ret} {name}({params(ps)})\n{{\n    return ep_{name}({', '.join(ps)});\n}}\n\n")
    return "".join(out)


def main():
    root = Path(sys.argv[1])
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_hi_shim.cc").write_text(shim(), newline="\n")
    (root / "heatindex.h").write_text(c_header(), newline="\n")
    (root / "heatindex.c").write_text(c_unit(), newline="\n")
    print(f"{len(FUNCS)} functions")


if __name__ == "__main__":
    main()
