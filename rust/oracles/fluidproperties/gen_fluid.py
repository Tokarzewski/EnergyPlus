"""Generate the FluidProperties oracle: a C++ shim over the real EnergyPlus code for the two
fluids every simulation has built in (water as a glycol, steam as a refrigerant), and a C unit
that rust-anything can bridge. Usage: python gen_fluid.py <out_dir>

Superheated steam is left out: its tables are compiled out (#ifdef UNUSED_FLUID_PROPS), so
InitConstantFluidPropertiesData fills HshValues and RhoshValues from arrays nobody initialises."""

import sys
from pathlib import Path

# (C name, fluid getter, method, params). Params are the doubles, in the original order.
FUNCS = [
    ("WaterSpecificHeat", "GetWater", "getSpecificHeat", ["Temperature"]),
    ("WaterSpecificHeat_raw", "GetWater", "getSpecificHeat_raw", ["Temperature"]),
    ("WaterDensity", "GetWater", "getDensity", ["Temperature"]),
    ("WaterConductivity", "GetWater", "getConductivity", ["Temperature"]),
    ("WaterViscosity", "GetWater", "getViscosity", ["Temperature"]),
    ("SteamSatPressure", "GetSteam", "getSatPressure", ["Temperature"]),
    ("SteamSatTemperature", "GetSteam", "getSatTemperature", ["Pressure"]),
    ("SteamSatEnthalpy", "GetSteam", "getSatEnthalpy", ["Temperature", "Quality"]),
    ("SteamSatDensity", "GetSteam", "getSatDensity", ["Temperature", "Quality"]),
    ("SteamSatSpecificHeat", "GetSteam", "getSatSpecificHeat", ["Temperature", "Quality"]),
]
# RefrigProps::getQuality is declared in FluidProperties.hh but defined nowhere, so it is not here.

HEADER = "// Generated by gen_fluid.py. Do not edit by hand.\n"


def params(ps):
    return ", ".join(f"double {p}" for p in ps)


def shim():
    out = [HEADER, """// Plain-double extern "C" entry points over the real EnergyPlus FluidProperties code. One
// EnergyPlusData for the process, with the built-in fluids (water, steam) initialised as
// init_constant_state does, and WarmupFlag set so the out-of-range warnings stay silent (they
// never change a result). A fatal error aborts the process, which the recorder records as a crash.
#include <cstdlib>
#include <exception>
#include <EnergyPlus/Data/EnergyPlusData.hh>
#include <EnergyPlus/DataGlobals.hh>
#include <EnergyPlus/FluidProperties.hh>

using namespace EnergyPlus;

namespace {
EnergyPlusData &st()
{
    static EnergyPlusData *s = [] {
        auto *p = new EnergyPlusData;
        Fluid::InitConstantFluidPropertiesData(*p);
        p->dataGlobal->WarmupFlag = true;
        return p;
    }();
    return *s;
}
// Build the state when the library loads: the recorder forks a child per case after loading,
// so each case starts from this same untouched state without paying for its construction.
[[maybe_unused]] EnergyPlusData &loaded = st();
} // namespace

extern "C" {
"""]
    for name, getter, method, ps in FUNCS:
        args = ", ".join(["st()"] + ps + ['"rust-anything"'])
        out.append(
            f"double ep_{name}({params(ps)})\n{{\n"
            f"    try {{\n        return Fluid::{getter}(st())->{method}({args});\n"
            f"    }} catch (...) {{\n        std::abort();\n    }}\n}}\n\n"
        )
    out.append("}\n")
    return "".join(out)


def c_header():
    out = [HEADER, "#ifndef EP_FLUIDPROPERTIES_H\n#define EP_FLUIDPROPERTIES_H\n\n"]
    for name, _, _, ps in FUNCS:
        out.append(f"double {name}({params(ps)});\n")
    out.append("\n#endif\n")
    return "".join(out)


def c_unit():
    out = [HEADER, """// The FluidProperties unit as rust-anything sees it: each function forwards to the real
// EnergyPlus code through libep_fluid_shim (shim/ep_fluid_shim.cc).
#include "fluidproperties.h"

"""]
    for name, _, _, ps in FUNCS:
        out.append(f"double ep_{name}({params(ps)});\n")
    out.append("\n")
    for name, _, _, ps in FUNCS:
        out.append(f"double {name}({params(ps)})\n{{\n    return ep_{name}({', '.join(ps)});\n}}\n\n")
    return "".join(out)


def main():
    root = Path(sys.argv[1])
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_fluid_shim.cc").write_text(shim(), newline="\n")
    (root / "fluidproperties.h").write_text(c_header(), newline="\n")
    (root / "fluidproperties.c").write_text(c_unit(), newline="\n")
    print(f"{len(FUNCS)} functions")


if __name__ == "__main__":
    main()
