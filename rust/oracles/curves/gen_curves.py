"""Generate the curve oracle: a C++ shim over the real EnergyPlus Curve::value for every
formula curve type, and a C unit that rust-anything can bridge. Usage: python gen_curves.py <out_dir>

Each C function takes the curve's coefficients, the min and max of each input, the output
minimum and maximum (NaN means the limit is not set) and the inputs, in that order, builds a
Curve and evaluates it with the overload of its own number of inputs, as CurveValue does.
Table curves (Btwxt) and EMS overrides are not in this unit."""

import sys
from pathlib import Path

# (C name, CurveType, number of coefficients, number of inputs)
CURVES = [
    ("CurveLinear", "Linear", 2, 1),
    ("CurveQuadratic", "Quadratic", 3, 1),
    ("CurveCubic", "Cubic", 4, 1),
    ("CurveQuartic", "Quartic", 5, 1),
    ("CurveExponent", "Exponent", 3, 1),
    ("CurveExponentialSkewNormal", "ExponentialSkewNormal", 4, 1),
    ("CurveSigmoid", "Sigmoid", 5, 1),
    ("CurveRectangularHyperbola1", "RectangularHyperbola1", 3, 1),
    ("CurveRectangularHyperbola2", "RectangularHyperbola2", 3, 1),
    ("CurveExponentialDecay", "ExponentialDecay", 3, 1),
    ("CurveDoubleExponentialDecay", "DoubleExponentialDecay", 5, 1),
    ("CurveBiQuadratic", "BiQuadratic", 6, 2),
    ("CurveQuadraticLinear", "QuadraticLinear", 6, 2),
    ("CurveCubicLinear", "CubicLinear", 6, 2),
    ("CurveBiCubic", "BiCubic", 10, 2),
    ("CurveFanPressureRise", "FanPressureRise", 4, 2),
    ("CurveChillerPartLoadWithLift", "ChillerPartLoadWithLift", 12, 3),
    ("CurveTriQuadratic", "TriQuadratic", 27, 3),
    ("CurveQuadLinear", "QuadLinear", 5, 4),
    ("CurveQuintLinear", "QuintLinear", 6, 5),
]

HEADER = "// Generated by gen_curves.py. Do not edit by hand.\n"


def names(nc, nv):
    ps = [f"c{i}" for i in range(nc)]
    for j in range(1, nv + 1):
        ps += [f"x{j}min", f"x{j}max"]
    ps += ["outmin", "outmax"]
    ps += [f"V{j}" for j in range(1, nv + 1)]
    return ps


def params(ps):
    return ", ".join(f"double {p}" for p in ps)


def shim():
    out = [HEADER, """// Plain-double extern "C" entry points over the real EnergyPlus Curve::value. One
// EnergyPlusData for the process, built when the library loads so each forked case starts from
// the same untouched state. A C++ exception aborts the process, which the recorder records as a crash.
#include <cmath>
#include <cstdlib>
#include <exception>
#include <EnergyPlus/CurveManager.hh>
#include <EnergyPlus/Data/EnergyPlusData.hh>

using namespace EnergyPlus;

namespace {
EnergyPlusData &st()
{
    static EnergyPlusData *s = [] { return new EnergyPlusData; }();
    return *s;
}
[[maybe_unused]] EnergyPlusData &loaded = st();

void set_output_limits(Curve::Curve &c, double outmin, double outmax)
{
    c.outputLimits.minPresent = !std::isnan(outmin);
    c.outputLimits.min = c.outputLimits.minPresent ? outmin : 0.0;
    c.outputLimits.maxPresent = !std::isnan(outmax);
    c.outputLimits.max = c.outputLimits.maxPresent ? outmax : 0.0;
}
} // namespace

extern "C" {
"""]
    for name, ctype, nc, nv in CURVES:
        body = [f"        Curve::Curve c;", f"        c.curveType = Curve::CurveType::{ctype};",
                f"        c.numDims = {nv};"]
        body += [f"        c.coeff[{i}] = c{i};" for i in range(nc)]
        for j in range(1, nv + 1):
            body.append(f"        c.inputLimits[{j - 1}].min = x{j}min;")
            body.append(f"        c.inputLimits[{j - 1}].max = x{j}max;")
        body.append("        set_output_limits(c, outmin, outmax);")
        body.append(f"        return c.value(st(), {', '.join(f'V{j}' for j in range(1, nv + 1))});")
        out.append(f"double ep_{name}({params(names(nc, nv))})\n{{\n    try {{\n"
                   + "\n".join(body) + "\n    } catch (...) {\n        std::abort();\n    }\n}\n\n")
    out.append("}\n")
    return "".join(out)


def c_header():
    out = [HEADER, "#ifndef EP_CURVES_H\n#define EP_CURVES_H\n\n"]
    for name, _, nc, nv in CURVES:
        out.append(f"double {name}({params(names(nc, nv))});\n")
    out.append("\n#endif\n")
    return "".join(out)


def c_unit():
    out = [HEADER, """// The curve unit as rust-anything sees it: each function forwards to the real EnergyPlus
// Curve::value through libep_curve_shim (shim/ep_curve_shim.cc).
#include "curves.h"

"""]
    for name, _, nc, nv in CURVES:
        out.append(f"double ep_{name}({params(names(nc, nv))});\n")
    out.append("\n")
    for name, _, nc, nv in CURVES:
        ps = names(nc, nv)
        out.append(f"double {name}({params(ps)})\n{{\n    return ep_{name}({', '.join(ps)});\n}}\n\n")
    return "".join(out)


def main():
    root = Path(sys.argv[1])
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_curve_shim.cc").write_text(shim(), newline="\n")
    (root / "curves.h").write_text(c_header(), newline="\n")
    (root / "curves.c").write_text(c_unit(), newline="\n")
    print(f"{len(CURVES)} functions")


if __name__ == "__main__":
    main()
