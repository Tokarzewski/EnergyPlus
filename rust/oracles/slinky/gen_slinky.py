"""Generate the Slinky oracle: a C++ shim over the real EnergyPlus GLHESlinky g-function code
(GroundHeatExchangers/Slinky.cc) and a C unit that rust-anything can bridge.
Usage: python gen_slinky.py <out_dir>

Every function takes the heat exchanger's geometry as plain numbers (configuration, coil diameter,
pitch and depth, trench spacing, number of trenches and of coils, soil diffusivity, pipe outer
radius). The shim builds a GLHESlinky from them and places the rings as calcGFunctions does
(X0(n) = pitch (n - 1), Y0(m) = (m - 1) spacing, Z0 = depth) before calling the method.

The unit's domain is where the C++ is defined: inputs that would make it index outside its arrays
(a trench or coil number outside 1..count, fewer than one trench or coil, fewer than one point in
doubleIntegral, a g-function index outside 0..count - 1, or a simulation length that gives no
g-function) return NaN instead."""

import sys
from pathlib import Path

HEADER = "// Generated by gen_slinky.py. Do not edit by hand.\n"

GEOM = [("int", "verticalConfig"), ("double", "coilDiameter"), ("double", "coilPitch"),
        ("double", "coilDepth"), ("double", "trenchSpacing"), ("int", "numTrenches"),
        ("int", "numCoils"), ("double", "diffusivity"), ("double", "outRadius")]
RINGS = [("int", "m"), ("int", "n"), ("int", "m1"), ("int", "n1")]
D = lambda *names: [("double", x) for x in names]
I = lambda *names: [("int", x) for x in names]

# (C name, extra params after the geometry, C++ call on the GLHESlinky `s`)
FUNCS = [
    ("SlinkyDistToCenter", RINGS, "s.distToCenter(m, n, m1, n1)"),
    ("SlinkyDistance", RINGS + D("eta", "theta"), "s.distance(m, n, m1, n1, eta, theta)"),
    ("SlinkyDistanceToFictRing", RINGS + D("eta", "theta"), "s.distanceToFictRing(m, n, m1, n1, eta, theta)"),
    ("SlinkyNearFieldResponse", RINGS + D("eta", "theta", "t"),
     "s.nearFieldResponseFunction(m, n, m1, n1, eta, theta, t)"),
    ("SlinkyMidFieldResponse", RINGS + D("t"), "s.midFieldResponseFunction(m, n, m1, n1, t)"),
    ("SlinkyIntegral", RINGS + D("t", "eta") + I("J0"), "s.integral(m, n, m1, n1, t, eta, J0)"),
    ("SlinkyDoubleIntegral", RINGS + D("t") + I("I0", "J0"), "s.doubleIntegral(m, n, m1, n1, t, I0, J0)"),
    ("SlinkyGFunction", D("maxSimYears") + I("k"), "gfunction(s, maxSimYears, k)"),
]


def params(ps):
    return ", ".join(f"{t} {n}" for t, n in ps)


def ret(name):
    return "double"


def guard(name, extra):
    names = [n for _, n in extra]
    conds = ["numTrenches < 1", "numCoils < 1"]
    if "m" in names:
        conds += ["m < 1", "m > numTrenches", "m1 < 1", "m1 > numTrenches",
                  "n < 1", "n > numCoils", "n1 < 1", "n1 > numCoils"]
    if "I0" in names:
        conds.append("I0 < 1")
    return f"    if ({' || '.join(conds)}) {{\n        return std::nan(\"\");\n    }}\n"


def shim():
    out = [HEADER, """// Plain extern "C" entry points over the real EnergyPlus GLHESlinky g-function code. One
// EnergyPlusData for the process, built when the library loads (with console output off, so
// calcGFunctions' progress message stays off stdout) so each forked case starts from the same
// untouched state.
#include <cmath>
#include <memory>
#include <EnergyPlus/Data/EnergyPlusData.hh>
#include <EnergyPlus/DataGlobals.hh>
#include <EnergyPlus/GroundHeatExchangers/ResponseFactors.hh>
#include <EnergyPlus/GroundHeatExchangers/Slinky.hh>

using namespace EnergyPlus;
using GroundHeatExchangers::GLHESlinky;

namespace {
EnergyPlusData &st()
{
    static EnergyPlusData *s = [] {
        auto *p = new EnergyPlusData;
        p->dataGlobal->printConsoleOutput = false;
        return p;
    }();
    return *s;
}
[[maybe_unused]] EnergyPlusData &loaded = st();

// A GLHESlinky with this geometry and its rings placed as calcGFunctions places them.
GLHESlinky make(int verticalConfig, double coilDiameter, double coilPitch, double coilDepth, double trenchSpacing,
                int numTrenches, int numCoils, double diffusivity, double outRadius)
{
    GLHESlinky s;
    s.verticalConfig = verticalConfig != 0;
    s.coilDiameter = coilDiameter;
    s.coilPitch = coilPitch;
    s.coilDepth = coilDepth;
    s.trenchSpacing = trenchSpacing;
    s.numTrenches = numTrenches;
    s.numCoils = numCoils;
    s.soil.diffusivity = diffusivity;
    s.pipe.outRadius = outRadius;
    s.X0.allocate(numCoils);
    s.Y0.allocate(numTrenches);
    for (int coil = 1; coil <= numCoils; ++coil) {
        s.X0(coil) = coilPitch * (coil - 1);
    }
    for (int trench = 1; trench <= numTrenches; ++trench) {
        s.Y0(trench) = (trench - 1) * trenchSpacing;
    }
    s.Z0 = coilDepth;
    return s;
}

// The number of g-functions calcGFunctions makes for this simulation length, as it computes it;
// 0 where that is not a positive count it can allocate.
int num_gfunctions(double maxSimYears)
{
    double const tLg_max = std::log10(maxSimYears * (356.0 * 24.0 * 60.0 * 60.0) / 3600.0);
    double const pairs = (tLg_max - -2.0) / 0.25 + 1;
    if (!(pairs >= 1.0 && pairs < 1.0e6) || !(maxSimYears * 12 < 2.0e9)) {
        return 0;
    }
    return static_cast<int>(pairs);
}

double gfunction(GLHESlinky &s, double maxSimYears, int k)
{
    if (k < 0 || k >= num_gfunctions(maxSimYears)) {
        return std::nan("");
    }
    s.maxSimYears = maxSimYears;
    s.myRespFactors = std::make_shared<GroundHeatExchangers::GLHEResponseFactors>();
    s.calcGFunctions(st());
    return s.myRespFactors->GFNC[k];
}
} // namespace

extern "C" {
"""]
    geom_args = ", ".join(n for _, n in GEOM)
    for name, extra, call in FUNCS:
        ps = GEOM + extra
        body = guard(name, extra)
        body += f"    GLHESlinky s = make({geom_args});\n    return {call};\n"
        out.append(f"{ret(name)} ep_{name}({params(ps)})\n{{\n{body}}}\n\n")
    out.append("}\n")
    return "".join(out)


def c_header():
    out = [HEADER, "#ifndef EP_SLINKY_H\n#define EP_SLINKY_H\n\n"]
    out += [f"{ret(name)} {name}({params(GEOM + extra)});\n" for name, extra, _ in FUNCS]
    out.append("\n#endif\n")
    return "".join(out)


def c_unit():
    out = [HEADER, """// The Slinky unit as rust-anything sees it: each function forwards to the real EnergyPlus
// GLHESlinky code through libep_slinky_shim (shim/ep_slinky_shim.cc).
#include "slinky.h"

"""]
    out += [f"{ret(name)} ep_{name}({params(GEOM + extra)});\n" for name, extra, _ in FUNCS]
    out.append("\n")
    for name, extra, _ in FUNCS:
        ps = GEOM + extra
        out.append(f"{ret(name)} {name}({params(ps)})\n{{\n    return ep_{name}({', '.join(n for _, n in ps)});\n}}\n\n")
    return "".join(out)


def main():
    root = Path(sys.argv[1])
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_slinky_shim.cc").write_text(shim(), newline="\n")
    (root / "slinky.h").write_text(c_header(), newline="\n")
    (root / "slinky.c").write_text(c_unit(), newline="\n")
    print(f"{len(FUNCS)} functions")


if __name__ == "__main__":
    main()
