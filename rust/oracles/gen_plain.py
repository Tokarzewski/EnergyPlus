"""Generate a plain-number oracle for any EnergyPlus module: a C++ shim of `extern "C"` wrappers
over the module's functions whose parameters are all plain numbers, and the C forwarder that
rust-anything bridges. Shared by the units in rust/oracles/<unit>/.

Usage: python3 gen_plain.py <out_dir> <unit> <header> <namespace> [names...]

<header> is relative to src/EnergyPlus (e.g. General.hh), <namespace> the C++ namespace the
functions live in (e.g. General); for a unit drawn from several headers, both are comma-separated
lists of the same length. With names, only those functions are exported, in that order;
otherwise every plain-number function in the header is. A name may be `cname=CppName` to export a
C++ overload under another name (a qualified name such as `EnergyPlus::Interp` is called as
written, for functions outside <namespace>, and so is a member call on a default object such
as `Ns::Type{}.fn`), and may end in `@<condition>@<value>`: outside the condition the
export returns the value instead of calling the C++, for inputs where the C++ is undefined
(ADR-009). Writes shim/ep_<unit>_shim.cc, <unit>.h and <unit>.c; the shim library is
libep_<unit>_shim.so (see build_shim.sh)."""

import re
import sys
from pathlib import Path

PARAM = re.compile(r"(?:const\s+)?(Real64|double|int|bool)\s+(?:const\s+)?(\w+)(?:\s*=\s*[^,]+)?$")
CTYPE = {"Real64": "double", "double": "double", "int": "int", "bool": "bool"}
DECL = re.compile(
    r"(?:^|\n)\s*(?:\[\[nodiscard\]\]\s*)?(?:(?:inline|constexpr|static)\s+)*(Real64|double|int|bool)\s+"
    r"(\w+)\s*\(([^;{)]*)\)\s*(?:noexcept\s*)?[;{]"
)


def functions(hh):
    """(name, return type, [(type, param)]) of every function in `hh` taking only plain numbers."""
    s = re.sub(r"//[^\n]*", "", Path(hh).read_text())
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    out, seen = [], set()
    for ret, name, args in DECL.findall(s):
        ps = [p.strip() for p in args.split(",") if p.strip()]
        ms = [PARAM.match(re.sub(r"\s+", " ", p)) for p in ps]
        if ps and all(ms) and name not in seen:
            seen.add(name)
            out.append((name, CTYPE[ret], [(CTYPE[m.group(1)], m.group(2)) for m in ms]))
    return out


def select(fns, names):
    """(C name, C++ call, return type, params, guard) for each export; `fns` holds
    (name, return type, params, namespace)."""
    if not names:
        return [(n, f"{ns}::{n}", r, ps, ()) for n, r, ps, ns in fns]
    by = {}
    for n, r, ps, ns in fns:
        by.setdefault(n, (r, ps, ns))
    out = []
    for spec in names:
        spec, *guard = spec.split("@")
        cname, _, cpp = spec.partition("=")
        cpp = cpp or cname
        base = re.split(r"::|\.", cpp)[-1]
        if base not in by:
            sys.exit(f"{base}: no plain-number function of that name in the headers")
        r, ps, ns = by[base]
        call = cpp if "::" in cpp else f"{ns}::{cpp}"  # a qualified name is called as written
        out.append((cname, call, r, ps, tuple(guard)))
    return out


def params(ps):
    return ", ".join(f"{t} {n}" for t, n in ps)


def main():
    out_dir, unit, header, ns, *names = sys.argv[1:]
    root = Path(out_dir)
    ep = Path(__file__).resolve().parents[2] / "src" / "EnergyPlus"  # rust/oracles/gen_plain.py
    headers, spaces = header.split(","), ns.split(",")
    if len(headers) != len(spaces):
        sys.exit("give one namespace per header")
    fns = select([(*f, s) for h, s in zip(headers, spaces) for f in functions(ep / h)], names)
    head = f"// Generated by gen_plain.py ({unit}). Do not edit by hand.\n"
    includes = "".join(f"#include <EnergyPlus/{h}>\n" for h in headers)

    shim = [head, f"""// Plain extern "C" entry points over the real EnergyPlus functions in {", ".join(headers)}.
#include <cmath>
#include <EnergyPlus/Data/BaseData.hh>
#include <EnergyPlus/EPVector.hh>
{includes}
using namespace EnergyPlus;

extern "C" {{
"""]
    for cname, cpp, ret, ps, guard in fns:
        args = ", ".join(n for _, n in ps)
        check = f"    if (!({guard[0]})) {{\n        return {guard[1]};\n    }}\n" if guard else ""
        shim.append(f"{ret} ep_{cname}({params(ps)})\n{{\n{check}    return {cpp}({args});\n}}\n\n")
    shim.append("}\n")

    include_guard = f"EP_{unit.upper()}_H"
    h = [head, f"#ifndef {include_guard}\n#define {include_guard}\n\n#include <stdbool.h>\n\n"]
    h += [f"{ret} {cname}({params(ps)});\n" for cname, _, ret, ps, _ in fns]
    h.append("\n#endif\n")

    c = [head, f"""// The {unit} unit as rust-anything sees it: each function forwards to the real EnergyPlus
// function through libep_{unit}_shim (shim/ep_{unit}_shim.cc).
#include "{unit}.h"

"""]
    c += [f"{ret} ep_{cname}({params(ps)});\n" for cname, _, ret, ps, _ in fns]
    c.append("\n")
    for cname, _, ret, ps, _ in fns:
        c.append(f"{ret} {cname}({params(ps)})\n{{\n    return ep_{cname}({', '.join(n for _, n in ps)});\n}}\n\n")

    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / f"ep_{unit}_shim.cc").write_text("".join(shim), newline="\n")
    (root / f"{unit}.h").write_text("".join(h), newline="\n")
    (root / f"{unit}.c").write_text("".join(c), newline="\n")
    for cname, _, ret, ps, guard in fns:
        print(cname, ret, [n for _, n in ps], *guard)


if __name__ == "__main__":
    main()
