HEADER = "// Generated by gen_psy.py. Do not edit by hand.\n"


def params(ps):
    return ", ".join(f"double {p}" for p in ps)


def shim():
    out = [HEADER, """// Plain-double extern "C" entry points over the real EnergyPlus Psychrometrics code,
// linked against libenergyplusapi. One EnergyPlusData for the process, with the psychrometric
// caches initialised and WarmupFlag set so the out-of-range warnings stay silent (they never
// change a result). A fatal error aborts the process, which the recorder records as a crash.
#include <cstdlib>
#include <exception>
#include <EnergyPlus/Data/EnergyPlusData.hh>
#include <EnergyPlus/DataGlobals.hh>
#include <EnergyPlus/Psychrometrics.hh>

using namespace EnergyPlus;

namespace {
EnergyPlusData &st()
{
    static EnergyPlusData *s = [] {
        auto *p = new EnergyPlusData;
        Psychrometrics::InitializePsychRoutines(*p);
        p->dataGlobal->WarmupFlag = true;
        return p;
    }();
    return *s;
}
} // namespace

extern "C" {
"""]
    for name, ps, needs in FUNCS:
        args = ", ".join((["st()"] if needs else []) + ps)
        out.append(
            f"double ep_{name}({params(ps)})\n{{\n"
            f"    try {{\n        return Psychrometrics::{name}({args});\n"
            f"    }} catch (...) {{\n        std::abort();\n    }}\n}}\n\n"
        )
    out.append("}\n")
    return "".join(out)


def c_header():
    out = [HEADER, "#ifndef EP_PSYCHROMETRICS_H\n#define EP_PSYCHROMETRICS_H\n\n"]
    for name, ps, _ in FUNCS:
        out.append(f"double {name}({params(ps)});\n")
    out.append("\n#endif\n")
    return "".join(out)


def c_unit():
    out = [HEADER, """// The Psychrometrics unit as rust-anything sees it: each function forwards to the real
// EnergyPlus code through libep_psy_shim (shim/ep_psy_shim.cc).
#include "psychrometrics.h"

"""]
    for name, ps, _ in FUNCS:
        out.append(f"double ep_{name}({params(ps)});\n")
    out.append("\n")
    for name, ps, _ in FUNCS:
        out.append(f"double {name}({params(ps)})\n{{\n    return ep_{name}({', '.join(ps)});\n}}\n\n")
    return "".join(out)


def main():
    root = Path(sys.argv[1])
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_psy_shim.cc").write_text(shim(), newline="\n")
    (root / "psychrometrics.h").write_text(c_header(), newline="\n")
    (root / "psychrometrics.c").write_text(c_unit(), newline="\n")
    print(f"{len(FUNCS)} functions")


if __name__ == "__main__":
    main()
