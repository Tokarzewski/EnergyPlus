"""Generate the convection oracle: a C++ shim over the real EnergyPlus convection correlations
(namespace Convect, ConvectionCoefficients.hh) and a C unit that rust-anything can bridge.
Usage: python gen_conv.py <out_dir> <path to ConvectionCoefficients.hh>

The unit is every Convect function whose parameters are all plain numbers: the correlations
themselves. Their overloads that take EnergyPlusData read zone and surface state and stay in
C++, calling these. The list is read from the header, so it follows upstream changes."""

import re
import sys
from pathlib import Path

HEADER = "// Generated by gen_conv.py. Do not edit by hand.\n"
PARAM = re.compile(r"(?:const\s+)?(Real64|double|int|bool)\s+(?:const\s+)?(\w+)(?:\s*=\s*[^,]+)?$")
CTYPE = {"Real64": "double", "double": "double", "int": "int", "bool": "bool"}


def functions(hh):
    s = re.sub(r"//[^\n]*", "", Path(hh).read_text())
    out = []
    for ret, name, args in re.findall(
        r"(?:^|\n)\s*(?:inline\s+)?(Real64|double|int|bool)\s+(\w+)\s*\(([^;{)]*)\)\s*[;{]", s
    ):
        ps = [p.strip() for p in args.split(",") if p.strip()]
        ms = [PARAM.match(re.sub(r"\s+", " ", p)) for p in ps]
        if ps and all(ms):
            out.append((name, CTYPE[ret], [(CTYPE[m.group(1)], m.group(2)) for m in ms]))
    return out


def params(ps):
    return ", ".join(f"{t} {n}" for t, n in ps)


def shim(fns):
    out = [HEADER, """// Plain extern "C" entry points over the real EnergyPlus convection correlations. They take
// no EnergyPlusData, so there is no state to build.
#include <EnergyPlus/ConvectionCoefficients.hh>

using namespace EnergyPlus;

extern "C" {
"""]
    for name, ret, ps in fns:
        args = ", ".join(n for _, n in ps)
        out.append(f"{ret} ep_{name}({params(ps)})\n{{\n    return Convect::{name}({args});\n}}\n\n")
    out.append("}\n")
    return "".join(out)


def c_header(fns):
    out = [HEADER, "#ifndef EP_CONVECTION_H\n#define EP_CONVECTION_H\n\n#include <stdbool.h>\n\n"]
    out += [f"{ret} {name}({params(ps)});\n" for name, ret, ps in fns]
    out.append("\n#endif\n")
    return "".join(out)


def c_unit(fns):
    out = [HEADER, """// The convection unit as rust-anything sees it: each function forwards to the real
// EnergyPlus correlation through libep_conv_shim (shim/ep_conv_shim.cc).
#include "convection.h"

"""]
    out += [f"{ret} ep_{name}({params(ps)});\n" for name, ret, ps in fns]
    out.append("\n")
    for name, ret, ps in fns:
        args = ", ".join(n for _, n in ps)
        out.append(f"{ret} {name}({params(ps)})\n{{\n    return ep_{name}({args});\n}}\n\n")
    return "".join(out)


def main():
    root, hh = Path(sys.argv[1]), sys.argv[2]
    fns = functions(hh)
    (root / "shim").mkdir(parents=True, exist_ok=True)
    (root / "shim" / "ep_conv_shim.cc").write_text(shim(fns), newline="\n")
    (root / "convection.h").write_text(c_header(fns), newline="\n")
    (root / "convection.c").write_text(c_unit(fns), newline="\n")
    print(f"{len(fns)} functions")


if __name__ == "__main__":
    main()
